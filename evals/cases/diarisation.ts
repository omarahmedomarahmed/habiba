import type { Alignment, AlignmentReason, SegmentWindow } from "@/lib/diarisation/align";
import type { AcousticTurn } from "@/lib/diarisation/turns";
import type { VoiceRole } from "@/lib/diarisation/voices";

/**
 * Recordings with known voices. PLAN.md 37.1, 37.2, 37.3.
 *
 * ## What these are for
 *
 * The half of sprint 37 that ships is arithmetic, and arithmetic can be
 * measured exactly rather than approximately. Each fixture is a recording
 * written by hand: the turns a diarisation provider would return, the chunks
 * the transcription model would return, and — separately — **what the answer
 * is**, decided by how the recording was constructed rather than by running
 * the code and writing down what it said.
 *
 * 🔴 That last distinction is the whole value. A fixture whose gold labels were
 * generated by the aligner is a test that the aligner agrees with itself, which
 * is the C84 family: a checker that matched its own helper. So the gold here is
 * derived from the construction — *voice A speaks during chunk 3, therefore the
 * answer for chunk 3 is A* — and a change to `align.ts` that breaks these
 * breaks them for a reason somebody can read.
 *
 * ## ⚠️ What they are NOT
 *
 * They are not a diarisation error rate. These turns are synthetic, exact, and
 * kind: real ones come from a provider listening to two people in a room with a
 * radiator, and they are wrong in ways no handwritten fixture predicts. The
 * acoustic DER is **gap 37.4**, named rather than absorbed, and it needs real
 * audio and a provider. What these measure is the layer between the provider
 * and the clinical record, which is where a wrong name actually gets written.
 */

export type GoldSegment = { label: string } | { refuse: AlignmentReason };

export type DiarisationFixture = {
  id: string;
  note: string;
  turns: AcousticTurn[];
  segments: SegmentWindow[];
  /** One entry per segment, in order. */
  gold: GoldSegment[];
  /** Rows a two-track capture already answered for: index to measured role. */
  measured: Array<[number, VoiceRole]>;
  expect: {
    /** Distinct voices in the recording. 37.3: however many there are. */
    voices: number;
    /** Label to the role the evidence proves, or null for unrecognised. */
    bound: Record<string, VoiceRole | null>;
    /** What the transcript shows, voice by voice, in first-heard order. */
    display: string[];
  };
};

