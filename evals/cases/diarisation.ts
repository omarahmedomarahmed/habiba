/** A fixture by id, for a test that wants to name the case it is about. */
export function fixture(id: string): DiarisationFixture {
  const found = DIARISATION_FIXTURES.find((f) => f.id === id);
  if (!found) throw new Error(`no diarisation fixture called ${id}`);
  return found;
}

/** Gold as the aligner's own shape, so a comparison is a comparison. */
export function goldMatches(gold: GoldSegment[], alignments: Alignment[]): string[] {
  const wrong: string[] = [];
  for (let i = 0; i < gold.length; i += 1) {
    const truth = gold[i]!;
    const got = alignments[i];
    if (!got) {
      wrong.push(`${i}: no alignment at all`);
      continue;
    }
    if ("label" in truth) {
      if (got.label !== truth.label) wrong.push(`${i}: ${got.label ?? got.reason} not ${truth.label}`);
      continue;
    }
    if (got.label !== null) wrong.push(`${i}: ${got.label} should have been refused as ${truth.refuse}`);
    else if (got.reason !== truth.refuse) wrong.push(`${i}: refused as ${got.reason} not ${truth.refuse}`);
  }
  return wrong;
}

export function measuredMap(fixture: DiarisationFixture): Map<number, VoiceRole> {
  return new Map(fixture.measured);
}
