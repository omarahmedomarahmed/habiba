/**
 * A clean alternating recording: each voice speaks one chunk's worth in turn.
 *
 * `turnMs` of speech then a `gapMs` breath, and one transcript chunk per turn.
 * This is the easy case, and it exists so that a regression which makes the
 * aligner refuse everything is impossible to miss: the refusal count is a
 * headline number precisely because refusing is otherwise free.
 */
function alternating(
  labels: string[],
  turnCount: number,
  turnMs = 8000,
  gapMs = 400,
): Pick<DiarisationFixture, "turns" | "segments" | "gold"> {
  const stride = turnMs + gapMs;
  const turns: AcousticTurn[] = [];
  const segments: SegmentWindow[] = [];
  const gold: GoldSegment[] = [];

  for (let i = 0; i < turnCount; i += 1) {
    const label = labels[i % labels.length]!;
    turns.push({ label, startMs: i * stride, endMs: i * stride + turnMs });
    segments.push({ index: i, startMs: i * stride, endMs: (i + 1) * stride });
    /* The answer comes from who was constructed to be speaking, not from code. */
    gold.push({ label });
  }

  return { turns, segments, gold };
}

